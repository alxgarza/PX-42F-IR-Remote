/* Writes tests/ir_vectors.h: what the Flipper firmware's own infrared
 * encoders send for one code of each protocol (see make.sh), which
 * irproto.c must match. */
#include <stdio.h>
#include "infrared.h"

#define TRANSMISSIONS 3

static const struct {
    const char *protocol;
    uint32_t address, command;
    int press; /* 1: the second press (RC5's and RC6's toggle bit set) */
} codes[] = {
        {"NEC", 0x07, 0x02, 0},          {"NECext", 0x7D02, 0x609F, 0},   {"NEC42", 0x1A5C, 0xC3, 0},
        {"NEC42ext", 0x2B4C6D1, 0xBEEF, 0}, {"Samsung32", 0x07, 0x02, 0}, {"RC6", 0x00, 0x0C, 0},
        {"RC6", 0x00, 0x0C, 1},           {"RC5", 0x00, 0x0C, 0},          {"RC5", 0x15, 0x2A, 1},
        {"RC5X", 0x0A, 0x55, 0},          {"SIRC", 0x01, 0x15, 0},         {"SIRC15", 0x97, 0x2A, 0},
        {"SIRC20", 0x1A5C, 0x33, 0},      {"Kaseikyo", 0x1802020, 0x2F3, 0}, {"RCA", 0x0F, 0x54, 0},
        {"Pioneer", 0xAA, 0x1C, 0},
};

int main(void) {
    printf("/* Generated by tools/ir_vectors/make.sh from the Flipper Zero firmware's\n"
           " * infrared encoders -- do not edit by hand. Each: a code, and what %d\n"
           " * transmissions of it send, in microseconds, off and on by turns from the\n"
           " * first gap (a trailing gap left off). */\n\n",
           TRANSMISSIONS);
    printf("#define IR_VECTOR_TRANSMISSIONS %d\n\n", TRANSMISSIONS);
    printf("static const struct {\n    const char *protocol;\n    uint32_t address, command;\n"
           "    bool toggle;\n    int count;\n    uint32_t us[400];\n} ir_vectors[] = {\n");
    for (size_t i = 0; i < sizeof(codes) / sizeof(codes[0]); i++) {
        InfraredEncoderHandler *h = infrared_alloc_encoder();
        InfraredMessage m = {.protocol = infrared_get_protocol_by_name(codes[i].protocol),
                             .address = codes[i].address, .command = codes[i].command};
        for (int p = 0; p <= codes[i].press; p++)
            infrared_reset_encoder(h, &m);
        static uint32_t us[400];
        int n = 0, last = -1, done = 0;
        while (done < TRANSMISSIONS) {
            uint32_t d;
            bool level;
            InfraredStatus st = infrared_encode(h, &d, &level);
            if (d != 0) {
                if (level == last)
                    us[n - 1] += d;
                else
                    us[n++] = d;
                last = level;
            }
            if (st == InfraredStatusDone)
                done++;
        }
        if (last == 0)
            n--;
        infrared_free_encoder(h);
        printf("        {\"%s\", 0x%X, 0x%X, %s, %d, {", codes[i].protocol, codes[i].address, codes[i].command,
               codes[i].press ? "true" : "false", n);
        for (int k = 0; k < n; k++)
            printf("%s%u", k == 0 ? "" : k % 16 == 0 ? ",\n            " : ", ", us[k]);
        printf("}},\n");
    }
    printf("};\n");
    return 0;
}
